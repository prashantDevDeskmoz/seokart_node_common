'use strict';

const { getStoreURL } = require('../bigcommerce/bigCapi');
const { getProductTemplateData } = require('../bigcommerce/productData');
const {
  getProductImage,
  createProductImage,
  updateProductImageAlt,
  deleteProductImage,
} = require('../bigcommerce/productImages');
const { LOSSLESS_QUALITY, MIME_BY_EXT, OPTIMIZE_RESULT } = require('./constants');
const { downloadImage, formatSizeKb } = require('./downloadImage');
const { compressImage, getQualityForLevel } = require('./compressImage');
const { getImageFileName, buildOptimizedFileName } = require('./fileName');
const { resolveImageSetting } = require('./imageSetting');
const { saveOriginalImage } = require('./localOriginal');

const failed = (message) => ({ success: false, status: OPTIMIZE_RESULT.FAILED, message });

const isSameFormat = (extA, extB) => {
  const normalize = (ext) => (ext === 'jpeg' ? 'jpg' : ext);
  return normalize(extA) === normalize(extB);
};

/**
 * Image bytes to upload: compressed when the file size setting is on, otherwise the
 * original (re-encoded only if the output format differs). Never bigger than the original.
 */
const buildOutputImage = async ({ original, outputExt, settingValue }) => {
  const sameFormat = isSameFormat(original.ext, outputExt);
  const keepOriginal = async () =>
    sameFormat
      ? original.buffer
      : compressImage(original.buffer, { outputExt, quality: LOSSLESS_QUALITY });

  if (settingValue.fileSizeStatus !== 1) {
    return keepOriginal();
  }

  const compressed = await compressImage(original.buffer, {
    outputExt,
    quality: getQualityForLevel(settingValue.imgQuality),
  });
  if (!compressed) return null;

  return compressed.length > original.buffer.length ? keepOriginal() : compressed;
};

/**
 * Optimize one BigCommerce product image using the store's image optimizer setting:
 * new file name, alt text and/or compressed file.
 * Port of ImgoptController@queue_image_optimization_api.
 *
 * This function does NOT touch the database. The caller:
 *   - checks plan limit / AI credits before calling (see getOptimizeLimitLeft)
 *   - saves the imgopt row (see buildImgoptRecord) and stores `newImageId` from the result
 *   - sets seo audit point8 when `altUpdated` is true
 *
 * Steps:
 *   1. Load image + product data from BigCommerce
 *   2. Resolve setting → file name, alt text, quality
 *   3. Alt only? → update alt text in place and stop
 *   4. Download original → compress / rename
 *   5. Upload new image, then delete the old one (BigCommerce can't replace a file)
 *
 * @param {object} params
 * @param {string} params.shop - store hash
 * @param {string} params.accessToken
 * @param {number|string} params.productId
 * @param {number|string} params.imageId
 * @param {object} params.setting - parsed imgopt_setting.setting
 * @param {object} [params.image] - BigCommerce image object if already loaded (saves one API call in bulk)
 * @param {string} [params.providedAltText] - alt text sent by the client; kept when the alt setting is off
 * @param {boolean} [params.skipAiAlt=false] - alt already generated by SEO Copilot; use providedAltText
 * @param {() => Promise<{ altText?: string, creditsExhausted?: boolean }>} [params.generateAiAlt]
 *        pass only when the store uses AI alt mode
 * @param {string} [params.originalBaseDir] - root of img_opt storage; when set, original is saved under
 *        `{originalBaseDir}/{shop}/original/{fileName}` (same as PHP)
 * @returns {Promise<{
 *   success: boolean, status: string, message: string,
 *   oldImageId?: number, newImageId?: number, fileName?: string, altText?: string,
 *   altUpdated?: boolean, originalSize?: string, optimizedSize?: string
 * }>}
 */
const optimizeProductImage = async ({
  shop,
  accessToken,
  productId,
  imageId,
  setting,
  image,
  providedAltText,
  skipAiAlt = false,
  generateAiAlt,
  originalBaseDir,
}) => {
  try {
    if (!setting) return failed('Image optimizer setting not found');

    // 1. Image + product data
    const productImage = image || (await getProductImage(shop, accessToken, productId, imageId));
    if (!productImage?.image_file) return failed('Product image not found');

    const needsProductData =
      Number(setting.file_name_status) === 1 || Number(setting.alt_status) === 1;
    const productData = needsProductData
      ? await getProductTemplateData(shop, accessToken, productId)
      : null;
    if (needsProductData && !productData) return failed('Product not found');

    // 2. Setting → file name, alt text, quality
    const settingValue = await resolveImageSetting({
      setting,
      productData,
      skipAiAlt,
      generateAiAlt,
    });
    if (settingValue.aiCreditsExhausted) {
      return {
        success: false,
        status: OPTIMIZE_RESULT.AI_CREDITS_EXHAUSTED,
        message: 'AI alt text credits exhausted',
      };
    }

    const currentAltText = providedAltText ?? productImage.description ?? '';
    let altText = currentAltText;
    if (settingValue.altStatus === 1) {
      const useProvidedAlt = skipAiAlt && String(providedAltText || '').trim() !== '';
      altText = useProvidedAlt ? String(providedAltText).trim() : settingValue.altText;
    }
    const altUpdated = settingValue.altStatus === 1;

    // 3. Alt only: update the description, no re-upload
    const isAltOnly =
      altUpdated && settingValue.fileSizeStatus !== 1 && settingValue.fileNameStatus !== 1;
    if (isAltOnly) {
      if (altText) {
        const updated = await updateProductImageAlt(shop, accessToken, productId, imageId, altText);
        if (!updated) return failed('BigCommerce alt text update failed');
      }
      return {
        success: true,
        status: OPTIMIZE_RESULT.ALT_UPDATED,
        message: 'Alt text updated',
        oldImageId: Number(imageId),
        newImageId: Number(imageId),
        altText,
        altUpdated,
      };
    }

    // 4. Download original → compress / rename
    const sourceUrl = `${getStoreURL(shop)}/product_images/${productImage.image_file}`;
    const original = await downloadImage(sourceUrl);
    if (!original) return failed('Could not download the original image');

    const fileName = buildOptimizedFileName({
      originalFileName: getImageFileName(productImage.image_file),
      imageId,
      settingValue,
      fallbackExt: original.ext,
    });
    const outputExt = fileName.split('.').pop();

    const outputBuffer = await buildOutputImage({ original, outputExt, settingValue });
    if (!outputBuffer) return failed('Could not compress the image');

    // 5. Upload new image, then remove the old one
    const newImage = await createProductImage({
      shop,
      accessToken,
      productId,
      buffer: outputBuffer,
      fileName,
      mime: MIME_BY_EXT[outputExt],
      description: altText,
      isThumbnail: Boolean(productImage.is_thumbnail),
      sortOrder: productImage.sort_order ?? 0,
    });
    if (!newImage?.id) return failed('BigCommerce image upload failed');

    await deleteProductImage(shop, accessToken, productId, imageId);

    // Same as PHP: keep a local copy of the original for restore
    if (originalBaseDir) {
      await saveOriginalImage({
        baseDir: originalBaseDir,
        storeHash: shop,
        fileName: getImageFileName(productImage.image_file),
        buffer: original.buffer,
      });
    }

    return {
      success: true,
      status: OPTIMIZE_RESULT.OPTIMIZED,
      message: 'Image optimized',
      oldImageId: Number(imageId),
      newImageId: newImage.id,
      fileName,
      image_file: newImage.image_file,
      url_thumbnail: newImage.url_thumbnail,
      altText,
      altUpdated,
      originalSize: original.sizeKb,
      optimizedSize: formatSizeKb(outputBuffer.length),
    };
  } catch (err) {
    console.error('optimizeProductImage error', { shop, productId, imageId, error: err.message });
    return failed(err.message);
  }
};

module.exports = {
  optimizeProductImage,
};
